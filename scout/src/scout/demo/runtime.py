"""`DemoRuntime`: the demo's composition root. One object builds, per repo, the real in-process
`GatewayService` over the real turbopuffer store (namespace family `scout_dev_demo_<name>`), the real Voyage
embedder (voyage-code-4, document/query input types, 1024 dims) and an OpenAI-compatible chat endpoint, then
drives the unchanged `ScoutApp` facade (sync = Merkle + encrypted rows + HMAC tokens; explore = the product
loop with grep/glob/read_file/semantic_search).

The demo holds a locally generated gateway master key (`<home>/master.key`, 0600). The per-repo team key is
generated by the gateway on first use and stored wrapped under that master key in the repo's `__keys`
namespace, exactly as in the product. Lose `master.key` and the repo's index becomes unreadable (re-index).
"""

