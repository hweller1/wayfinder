Log = Callable[[str], None]

VOYAGE_USD_PER_M_TOKENS = 0.18  # voyage-code-3 list price; code-4 price is doc-only, so this is an estimate
H100_USD_PER_HOUR = 3.95  # Modal H100 list price; the explore cost estimate is wall time at this rate
CHARS_PER_TOKEN = 3.5
CLONE_TIMEOUT_S = 600


def stderr_log(msg: str) -> None:
    print(msg, file=sys.stderr, flush=True)


@dataclass(frozen=True, slots=True)
class ModelConfig:
    label: str
    base_url: str
    model: str
    api_key: str | None
    usd_per_hour: float = 0.0  # self-hosted GPU rate; hosted APIs leave this at 0 (cost not estimated)
    sampling: str = (
        "a1"  # OpenAIChat sampling profile: `a1` (top_k, penalty, thinking flag) or `sft` (temp + top_p)
    )


def resolve_model(
    env: Mapping[str, str],
    *,
    preset: str | None = None,
    base_url: str | None = None,
    model: str | None = None,
    api_key: str | None = None,
) -> ModelConfig:
    """`--model-base-url/--model/--api-key` win; else the preset (`SCOUT_DEMO_PRESET` if set, else `a1` when
    A1_BASE_URL is set, `baseten` when only BASETEN_API_KEY is); `v3` reads V3_BASE_URL/V3_API_KEY
    (wayfinder-glimmer, served as wayfinder-v3; serve/wayfinder_v3.py); `scout` reads
    SCOUT_LLM_URL/KEY/MODEL/SAMPLING."""
    if base_url:
        return ModelConfig("custom", base_url, model or "a1", api_key or env.get("SCOUT_LLM_API_KEY"))
    choice = (
        preset
        or env.get("SCOUT_DEMO_PRESET")
        or ("a1" if env.get("A1_BASE_URL") else "baseten" if env.get("BASETEN_API_KEY") else "")
    )
    if choice == "a1":
        if not env.get("A1_BASE_URL"):
            raise ScoutError(
                ErrorCode.INVALID_ARGUMENT, "A1_BASE_URL is not set (wayfinder/.env); use --preset baseten"
            )
        return ModelConfig(
            "agents-a1-35b (Modal H100)",
            env["A1_BASE_URL"],
            model or env.get("A1_MODEL", "a1"),
            api_key or env.get("A1_API_KEY"),
            usd_per_hour=H100_USD_PER_HOUR,
        )
    if choice == "v3":
        if not env.get("V3_BASE_URL"):
            raise ScoutError(
                ErrorCode.INVALID_ARGUMENT, "V3_BASE_URL is not set (wayfinder/.env); use --preset a1"
            )
        return ModelConfig(
            "wayfinder-glimmer (Modal H100)",
            env["V3_BASE_URL"],
            model or env.get("V3_MODEL", "wayfinder-v3"),
            api_key or env.get("V3_API_KEY"),
            usd_per_hour=H100_USD_PER_HOUR,
            sampling="sft",
        )
    if choice == "baseten":
        return ModelConfig(
            "muse-spark-open (Baseten)",
            "https://inference.baseten.co/v1",
            model or "meta-models/muse-spark-open",
            api_key or env.get("BASETEN_API_KEY"),
        )
    if choice == "scout" and env.get("SCOUT_LLM_URL"):
        return ModelConfig(
            "scout-llm",
            env["SCOUT_LLM_URL"],
            model or env.get("SCOUT_LLM_MODEL", "scout-llm"),
            api_key or env.get("SCOUT_LLM_API_KEY"),
            sampling=sampling_profile_from_env(env),
        )
    raise ScoutError(
        ErrorCode.INVALID_ARGUMENT,
        "no chat model configured: set A1_BASE_URL/A1_API_KEY, V3_BASE_URL/V3_API_KEY, BASETEN_API_KEY, "
        "or pass --model-base-url",
    )


class MeteredEmbedder:
    """Counts what the real embedder is asked and charged for, and reports progress."""

    def __init__(self, inner: Embedder, log: Log) -> None:
        self._inner = inner
        self._log = log
        self.dims = inner.dims
        self.model = inner.model
        self.doc_tokens = 0
        self.doc_texts = 0
        self.query_tokens = 0

    async def count_tokens(self, texts: Sequence[str]) -> int:
        return await self._inner.count_tokens(texts)

    async def embed(self, texts: Sequence[str], *, input_type: Literal["document", "query"]) -> EmbedResult:
        res = await self._inner.embed(texts, input_type=input_type)
        if input_type == "document":
            self.doc_tokens += res.tokens
            self.doc_texts += len(texts)
            self._log(f"  embedded {self.doc_texts} chunks so far ({self.doc_tokens:,} Voyage tokens)")
        else:
            self.query_tokens += res.tokens
        return res


@dataclass(slots=True)
class IndexReport:
    name: str
    namespace: str
    root: str
    files: int
    chunks: int
    voyage_tokens: int
    est_cost_usd: float
    state: str
    coverage: float
    seconds: float
    already_indexed: bool = False
    warnings: list[str] = field(default_factory=lambda: [])

    def to_dict(self) -> dict[str, Any]:
        return {k: getattr(self, k) for k in self.__slots__}


@dataclass(slots=True)
class ExploreReport:
    repo: str
    result: ExploreResult
    model: str
    est_cost_usd: float | None
    cost_basis: str
    wall_s: float
    warmup_s: float = 0.0

    def to_dict(self) -> dict[str, Any]:
        data = self.result.model_dump(by_alias=True, mode="json")
        data["usage"]["cost_usd"] = self.est_cost_usd
        return {
            "repo": self.repo,
            "model": self.model,
            "cost_basis": self.cost_basis,
            "wall_s": round(self.wall_s, 2),
            "warmup_s": round(self.warmup_s, 2),
            **data,
        }


def looks_remote(source: str) -> bool:
    return "://" in source or source.startswith("git@") or bool(re.match(r"^[\w.-]+\.\w+:[\w./-]+$", source))


def default_name(source: str) -> str:
    base = source.rstrip("/").rsplit("/", 1)[-1].rsplit(":", 1)[-1]
    return sanitize_name(base.removesuffix(".git"))


def estimate_cost(tokens: int) -> float:
    return tokens * VOYAGE_USD_PER_M_TOKENS / 1_000_000


class DemoRuntime:
    def __init__(
        self,
        *,
        env: Mapping[str, str] | None = None,
        home: Path | None = None,
        store: VectorStore | None = None,
        embedder: Embedder | None = None,
        chat: ChatModel | None = None,
        log: Log = stderr_log,
    ) -> None:
        self.env = dict(load_env() if env is None else env)
        self.home = home or demo_home(self.env)
        self.home.mkdir(parents=True, exist_ok=True, mode=0o700)
        self.registry = Registry(self.home)
        self._store = store
        self._embedder = embedder
        self._chat = chat
        self._log = log
        self.clock = SystemClock()

    # --- real adapters (lazy, so `list` and `--help` never touch the network) -----------------------
    def _real_store(self) -> VectorStore:
        if self._store is None:
            from scout.adapters.turbopuffer import TurbopufferStore

            self._store = TurbopufferStore.from_env(self.env)
        return self._store

    def _real_embedder(self) -> Embedder:
        if self._embedder is None:
            from scout.adapters.voyage import VoyageEmbedder

            self._embedder = VoyageEmbedder.from_env(self.env, clock=self.clock)
        return self._embedder

    def _master_key(self) -> bytes:
        path = self.home / "master.key"
        try:
            key = path.read_bytes()
        except FileNotFoundError:
            key = secrets.token_bytes(MASTER_KEY_LEN)
            fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(fd, "wb") as f:
                f.write(key)
        if len(key) != MASTER_KEY_LEN:
            raise ScoutError(ErrorCode.INTERNAL, "demo master.key has the wrong size; delete it and re-index")
        return key

    def _gateway(self, name: str, chat: ChatModel | None, embedder: Embedder) -> Any:
        store = DemoNamespaceStore(self._real_store(), name)
        limits = Limits(embed_tokens_per_min=500_000_000.0, search_per_s=50.0, search_burst=200.0)
        service = GatewayService(
            store,
            self.clock,
            self._master_key(),
            keys_namespace=KEYS_NS,
            embedder=embedder,
            chat=chat,
            limiter=RateLimiter(self.clock, limits),
        )
        return service.for_tenant(TENANT)

    def _app(self, rec_root: str, name: str, chat: ChatModel | None, embedder: Embedder) -> ScoutApp:
        fs = LocalFileSystem(rec_root)
        gateway = self._gateway(name, chat, embedder)
        return ScoutApp(
            gateway, fs, self.clock, sync_config=SyncConfig(), backfill_to=backfill_setting(os.environ)
        )

    # --- source handling -----------------------------------------------------------------------------
    def _checkout(self, source: str, name: str) -> tuple[str, bool]:
        """`(root, cloned)`: a shallow clone under `<home>/repos/<name>` for a URL, else the local path."""
        if not looks_remote(source):
            root = Path(source).expanduser().resolve()
            if not (root / ".git").exists():
                raise ScoutError(ErrorCode.NOT_A_REPO, f"{source} is not a git checkout")
            return str(root), False
        dest = self.home / "repos" / name
        if (dest / ".git").exists():
            self._log(f"using existing clone {dest}")
            return str(dest), False
        dest.parent.mkdir(parents=True, exist_ok=True)
        git = shutil.which("git")
        if git is None:
            raise ScoutError(ErrorCode.INTERNAL, "git executable not found")
        self._log(f"cloning {source} (shallow) -> {dest}")
        proc = subprocess.run(  # noqa: S603
            [git, "clone", "--depth", "1", "--quiet", "--", source, str(dest)],
            capture_output=True,
            text=True,
            timeout=CLONE_TIMEOUT_S,
            check=False,
            env={**os.environ, "GIT_TERMINAL_PROMPT": "0"},
        )
        if proc.returncode != 0:
            raise ScoutError(ErrorCode.NOT_FOUND, f"git clone failed: {proc.stderr.strip()[:300]}")
        return str(dest), True

    # --- index ---------------------------------------------------------------------------------------
    async def index(self, source: str, name: str | None = None, *, full: bool = False) -> IndexReport:
        repo_name = sanitize_name(name) if name else default_name(source)
        t0 = time.monotonic()
        root, _ = await asyncio.to_thread(self._checkout, source, repo_name)
        fs = LocalFileSystem(root)
        listing = await asyncio.to_thread(list_indexable, fs, Matcher.from_fs(fs))
        size = sum(
            await asyncio.gather(*(asyncio.to_thread(lambda p=p: fs.stat(p).size) for p in listing.paths))
        )
        est_tokens = int(size / CHARS_PER_TOKEN)
        self._log(
            f"indexing {repo_name}: {len(listing.paths)} files, {size / 1e6:.2f} MB; "
            f"est ~{est_tokens:,} Voyage tokens (~${estimate_cost(est_tokens):.3f} at "
            f"${VOYAGE_USD_PER_M_TOKENS}/M); namespace {namespace_for(repo_name)}"
        )
        for w in listing.warnings:
            self._log(f"  warning: {w}")
        meter = MeteredEmbedder(self._real_embedder(), self._log)
        app = self._app(root, repo_name, None, meter)
        status = await app.sync(True, full=full)
        state = StateDir.open(fs).read_state()
        tree = StateDir.open(fs).load_tree(state.last_branch) if state.last_branch else None
        chunks = sum(e.chunks for e in tree.files.values()) if tree else 0
        cost = estimate_cost(meter.doc_tokens)
        secs = time.monotonic() - t0
        rec = RepoRecord(
            name=repo_name,
            root=root,
            source=source,
            namespace=namespace_for(repo_name),
            repo_id=state.repo_id or "",
            branch_id=state.last_branch or "",
            files=status.files or len(listing.paths),
            chunks=chunks,
            voyage_tokens=meter.doc_tokens,
            est_cost_usd=round(cost, 5),
            state=status.state,
            coverage=status.coverage,
            indexed_at=time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        )
        old = self.registry.get(repo_name)
        if old and meter.doc_tokens == 0:  # an up-to-date re-run embeds nothing: keep the first run's stats
            rec.voyage_tokens, rec.est_cost_usd = old.voyage_tokens, old.est_cost_usd
        self.registry.put(rec)
        self._log(
            f"done in {secs:.1f}s: state={status.state} coverage={status.coverage:.2f} files={rec.files} "
            f"chunks={chunks}; Voyage tokens this run {meter.doc_tokens:,} (~${cost:.4f})"
        )
        return IndexReport(
            name=repo_name,
            namespace=rec.namespace,
            root=root,
            files=rec.files,
            chunks=chunks,
            voyage_tokens=meter.doc_tokens,
            est_cost_usd=round(cost, 5),
            state=status.state,
            coverage=status.coverage,
            seconds=round(secs, 2),
            already_indexed=bool(old) and meter.doc_tokens == 0,
            warnings=list(listing.warnings),
        )

    # --- explore -------------------------------------------------------------------------------------
    def chat_for(self, cfg: ModelConfig) -> ChatModel:
        if self._chat is not None:
            return self._chat
        return OpenAIChat(
            cfg.base_url,
            cfg.api_key,
            cfg.model,
            timeout=900.0,
            retain_reasoning=retain_reasoning_from_env(self.env),
            sampling=cfg.sampling,
        )

    async def warmup(self, cfg: ModelConfig) -> float:
        """One tiny completion so a scale-to-zero endpoint is up before the explore budget starts."""
        if self._chat is not None:
            return 0.0
        headers = {"Authorization": f"Bearer {cfg.api_key}"} if cfg.api_key else {}
        body = {"model": cfg.model, "messages": [{"role": "user", "content": "ping"}], "max_tokens": 1}
        t0 = time.monotonic()
        try:
            async with httpx.AsyncClient(timeout=900.0) as client:
                await client.post(cfg.base_url.rstrip("/") + "/chat/completions", headers=headers, json=body)
        except httpx.HTTPError:
            pass  # the explore call reports a real error with a typed code
        return time.monotonic() - t0

    async def warm_start(self, cfg: ModelConfig) -> tuple[str, float]:
        """Non-blocking cold-start trigger when the model has a Modal `/warm` endpoint (about 1 s), else the
        blocking 1-token `warmup`. Returns `(mode, seconds)`."""
        from scout.adapters.openai_chat.client import warm_url_for

        url = warm_url_for(cfg.base_url)
        if url:
            headers = {"Authorization": f"Bearer {cfg.api_key}"} if cfg.api_key else {}
            t0 = time.monotonic()
            try:
                async with httpx.AsyncClient(timeout=10.0) as client:
                    res = await client.get(url, headers=headers)
                if res.status_code == 200:
                    return "endpoint", time.monotonic() - t0
            except httpx.HTTPError:
                pass
        return "completion", await self.warmup(cfg)

    async def explore(
        self,
        brief: str,
        repo: str,
        cfg: ModelConfig,
        *,
        max_results: int = 12,
        max_turns: int = 40,
        max_seconds: int = 240,
        warmup: bool = True,
    ) -> ExploreReport:
        rec = self.registry.get(sanitize_name(repo))
        if rec is None:
            known = ", ".join(sorted(self.registry.load())) or "none"
            raise ScoutError(ErrorCode.NOT_FOUND, f"repo {repo!r} is not indexed (indexed: {known})")
        if not await asyncio.to_thread(Path(rec.root).is_dir):
            raise ScoutError(ErrorCode.NOT_FOUND, f"checkout {rec.root} is gone; re-run index")
        warm = 0.0
        if warmup:
            self._log(f"warming {cfg.label} ...")
            warm = await self.warmup(cfg)
            self._log(f"  model ready in {warm:.1f}s")
        meter = MeteredEmbedder(self._real_embedder(), lambda _m: None)
        app = self._app(rec.root, rec.name, self.chat_for(cfg), meter)
        t0 = time.monotonic()
        result = await app.explore(
            ExploreRequest(
                brief=brief,
                max_results=max_results,
                budget=Budget(max_turns=max_turns, max_seconds=max_seconds),
            )
        )
        wall = time.monotonic() - t0
        if cfg.usd_per_hour > 0:
            cost: float | None = round(wall * cfg.usd_per_hour / 3600 + estimate_cost(meter.query_tokens), 5)
            basis = f"wall time x ${cfg.usd_per_hour}/h GPU (single stream, upper bound) + query embeds"
        else:
            cost, basis = None, "hosted endpoint: price not estimated"
        return ExploreReport(rec.name, result, cfg.label, cost, basis, wall, warm)

    def list_repos(self) -> list[RepoRecord]:
        return sorted(self.registry.load().values(), key=lambda r: r.name)


def render_report(rep: ExploreReport) -> str:
    r = rep.result
    lines = [
        f"{h.path}:{h.start_line}-{h.end_line}  {' '.join(h.why.split())}  [{h.source}]"
        + ("" if h.verified else " (unverified)")
        for h in r.results
    ]
    out = [*lines, "", f"summary: {' '.join(r.summary.split())}"]
    out += [f"gap: {' '.join(g.split())}" for g in r.gaps]
    u = r.usage
    cost = f"${rep.est_cost_usd:.4f}" if rep.est_cost_usd is not None else "n/a"
    out.append(
        f"-- turns={u.turns} tools={u.tool_calls} tokens in/out={u.model_tokens.in_}/{u.model_tokens.out} "
        f"wall={rep.wall_s:.1f}s (+{rep.warmup_s:.1f}s warmup) est_cost={cost} model={rep.model} "
        f"index={r.index.state}@{r.index.coverage:.2f}" + (" BUDGET-EXHAUSTED" if r.budget_exhausted else "")
    )
    return "\n".join(out)
